"""
Automated Test Synthesizer.
Discovers untested modules and synthesizes automated pytest suites ensuring basic regression protection.
"""

import os
from typing import List
from .base import BaseOptimizer
from core.models import RepoHealthReport


class TestSynthesizerOptimizer(BaseOptimizer):
    __test__ = False

    def __init__(self):
        super().__init__(name="Automated Test Synthesizer")

    def optimize(self, repo_path: str, report: RepoHealthReport) -> List[str]:
        changes: List[str] = []

        if report.primary_language != "Python":
            # For non-python languages, ensure test directories exist
            tests_dir = os.path.join(repo_path, "tests")
            if not os.path.exists(tests_dir):
                os.makedirs(tests_dir, exist_ok=True)
                changes.append("Created standard tests/ directory for test suite organization")
            return changes

        # Check Python project tests
        tests_dir = os.path.join(repo_path, "tests")
        os.makedirs(tests_dir, exist_ok=True)

        init_file = os.path.join(tests_dir, "__init__.py")
        if not os.path.exists(init_file):
            with open(init_file, "w", encoding="utf-8") as f:
                f.write('"""Test suite package marker."""\n')

        # Check existing test files
        existing_test_files = [f for f in os.listdir(tests_dir) if f.startswith("test_") and f.endswith(".py")]

        if not existing_test_files:
            # Discover top-level python modules to test
            top_modules = []
            for item in os.listdir(repo_path):
                if item.endswith(".py") and item not in ("setup.py", "run.py", "conftest.py") and not item.startswith("."):
                    mod_name = os.path.splitext(item)[0]
                    top_modules.append(mod_name)

            # Synthesize test suite
            test_content = self._generate_integrity_test(top_modules)
            test_file_path = os.path.join(tests_dir, "test_integrity.py")
            with open(test_file_path, "w", encoding="utf-8") as f:
                f.write(test_content)

            changes.append(f"Synthesized automated unit test suite in tests/test_integrity.py testing {len(top_modules)} modules")

        return changes

    def _generate_integrity_test(self, modules: List[str]) -> str:
        code_lines = [
            '"""',
            'Automated Regression & Architectural Integrity Test Suite.',
            'Generated by GitHub Nightly Optimizer.',
            '"""',
            '',
            'import pytest',
            'import importlib',
            'import sys',
            'import os',
            '',
            '# Ensure repo root is on sys.path',
            'REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))',
            'if REPO_ROOT not in sys.path:',
            '    sys.path.insert(0, REPO_ROOT)',
            '',
        ]

        if not modules:
            code_lines.extend([
                'def test_baseline_environment():',
                '    """Verify basic python environment integrity."""',
                '    assert sys.version_info >= (3, 8)',
                '    assert True',
                ''
            ])
        else:
            code_lines.append(f"MODULES = {repr(modules)}")
            code_lines.extend([
                '',
                '@pytest.mark.parametrize("module_name", MODULES)',
                'def test_module_import_integrity(module_name):',
                '    """Verify all top-level modules can be imported cleanly without syntax/import errors."""',
                '    try:',
                '        mod = importlib.import_module(module_name)',
                '        assert mod is not None',
                '    except ImportError as e:',
                '        pytest.skip(f"Optional external dependency missing for {module_name}: {e}")',
                '',
                'def test_environment_validity():',
                '    """Verify python execution environment and system path validity."""',
                '    assert os.path.isdir(REPO_ROOT)',
                ''
            ])

        return "\n".join(code_lines)
